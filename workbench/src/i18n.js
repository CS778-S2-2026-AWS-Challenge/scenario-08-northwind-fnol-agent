let activeLanguage = initialLanguage()
const listeners = new Set()

function initialLanguage() {
  if (typeof document === 'undefined') return DEFAULT_LANGUAGE
  return document.documentElement.lang === 'zh-CN' ? 'zh-CN' : DEFAULT_LANGUAGE
}

export function normalizeLanguage(language) {
  return SUPPORTED_LANGUAGES.has(language) ? language : DEFAULT_LANGUAGE
}

export function getLanguage() {
  return activeLanguage
}

export function languageLocale(language = activeLanguage) {
  return normalizeLanguage(language) === 'zh-CN' ? 'zh-CN' : 'en-NZ'
}

export function setLanguage(language) {
  const next = normalizeLanguage(language)
  if (typeof document !== 'undefined') document.documentElement.lang = next
  if (next === activeLanguage) return
  activeLanguage = next
  listeners.forEach((listener) => listener())
}

export function translate(source, values = {}) {
  const template = activeLanguage === 'zh-CN' ? ZH_CN[source] || source : source
  return template.replace(/\{(\w+)\}/g, (match, key) => (
    values[key] === undefined || values[key] === null ? match : String(values[key])
  ))
}

export function useLanguage() {
  return useSyncExternalStore(
    (listener) => {
      listeners.add(listener)
      return () => listeners.delete(listener)
    },
    getLanguage,
    () => DEFAULT_LANGUAGE,
  )
}
